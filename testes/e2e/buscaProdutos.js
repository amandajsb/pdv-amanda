import electron from 'electron';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
const { app } = electron;
const pasta = fs.mkdtempSync(path.join(os.tmpdir(),'pdv-busca-e2e-'));
app.setPath('userData',pasta);
process.argv.push('--fiado-demo');
const { abrirBanco, fecharBanco } = await import('../../src/main/db/conexao.js');
const { registrarIpc } = await import('../../src/main/ipc/registrarIpc.js');
const { registrarEsquemaPrivilegiado, registrarProtocolo, criarJanela } = await import('../../src/main/janela.js');
const produtos = await import('../../src/main/repos/produtosRepo.js');
const estoque = await import('../../src/main/repos/estoqueRepo.js');
const log = {info(){},warn(){},error(e){console.error(e);}};
registrarEsquemaPrivilegiado();
const limite = setTimeout(()=>{console.error('Tempo limite');app.exit(1);},60000);
app.whenReady().then(async()=>{
  const db = abrirBanco(path.join(pasta,'ficticio.db'),{log});
  const criar = (nome,codigo) => db.transaction(()=>{
    const id=produtos.criar({nome,precoCentavos:1000,codigos:[codigo]});
    estoque.lancar(id,'inventario',20000,{motivo:'Teste fictício'});
    return id;
  })();
  const arroz=criar('Arroz branco fictício','ARROZ01');
  criar('Arroz integral fictício','ARROZ02');
  criar('Açúcar cristal fictício','ACUCAR01');
  const codigo=criar('Produto código prioritário fictício','ARR');
  const antigo=criar('Arroz antigo fictício','ANTIGO01');produtos.inativar(antigo);
  registrarProtocolo({log});registrarIpc({log});
  const win=criarJanela({log,mostrar:false});
  const wc=win.webContents;
  const erros=[];wc.on('console-message',e=>{if(e.level==='error')erros.push(e.message);});
  const exec=js=>wc.executeJavaScript(js,true);
  const ate=async js=>{for(let i=0;i<150;i++){if(await exec(js))return;await new Promise(r=>setTimeout(r,50));}throw new Error(js);};
  const digitar=async texto=>{await exec(`(()=>{const c=document.querySelector('#scan-input');c.focus();c.value=${JSON.stringify(texto)};c.dispatchEvent(new Event('input',{bubbles:true}));})()`);};
  const tecla=tecla=>exec(`document.querySelector('#scan-input').dispatchEvent(new KeyboardEvent('keydown',{key:${JSON.stringify(tecla)},bubbles:true}))`);
  const check=(nome,condicao)=>{assert.ok(condicao,nome);console.log('ok — '+nome);};
  let falhou=false;
  try{
    await new Promise(r=>wc.once('did-finish-load',r));
    await ate(`document.querySelector('#hdr-versao').textContent.includes('DEMONSTRAÇÃO')`);
    await digitar('arr');
    await ate(`!document.querySelector('#scan-sugestoes').hidden && document.querySelectorAll('[data-produto-indice]').length===3`);
    check('lista por iniciais sem Enter e exclui inativos',await exec(`document.querySelector('#scan-sugestoes').textContent.includes('Arroz branco') && !document.querySelector('#scan-sugestoes').textContent.includes('Arroz antigo')`));
    await exec(`document.querySelector('[data-produto-indice="0"]').click()`);
    await ate(`document.querySelector('#receipt-body').textContent.includes('Arroz branco')`);
    check('clique adiciona o produto e limpa a busca',await exec(`document.querySelector('#scan-input').value==='' && document.querySelector('#scan-sugestoes').hidden`));
    await digitar('acuc');
    await ate(`document.querySelector('#scan-sugestoes').textContent.includes('Açúcar')`);
    await tecla('ArrowDown');await tecla('Enter');
    await ate(`document.querySelector('#receipt-body').textContent.includes('Açúcar')`);
    check('busca sem acento e seleção pelo teclado',await exec(`document.querySelector('#receipt-body').textContent.includes('Arroz branco')`));
    await digitar('ARR');
    await ate(`document.querySelectorAll('[data-produto-indice]').length===3`);
    await tecla('Enter');
    await ate(`document.querySelector('#receipt-body').textContent.includes('Produto código prioritário')`);
    check('código exato do leitor tem prioridade sobre as sugestões',Boolean(codigo));
    await digitar('3*ARR');await tecla('Enter');
    await ate(`document.querySelector('#cart-total').textContent.includes('60,00')`);
    check('multiplicador por código continua funcionando',await exec(`document.querySelector('#receipt-body').textContent.includes('Produto código prioritário')`));
    await digitar('zzz-inexistente');
    await ate(`document.querySelector('#scan-sugestoes').textContent.includes('Nenhum produto')`);
    check('busca sem resultados não abre cadastro sozinha',await exec(`!document.querySelector('#modal-fundo').classList.contains('show')`));
    await tecla('Escape');
    check('Escape fecha sugestões',await exec(`document.querySelector('#scan-sugestoes').hidden`));
    await tecla('F2');
    await ate(`Boolean(document.querySelector('#bp-termo'))`);
    await exec(`(()=>{const c=document.querySelector('#bp-termo');c.value='inte';c.dispatchEvent(new Event('input',{bubbles:true}));})()`);
    await ate(`document.querySelector('#bp-lista').textContent.includes('Arroz integral')`);
    check('busca F2 continua encontrando nomes parciais',true);
    check('pesquisar e montar carrinho não movimenta estoque',produtos.porId(arroz).estoque_milesimal===20000);
    check('sem erros de JavaScript',erros.length===0);
  }catch(e){falhou=true;console.error(e.stack);}
  clearTimeout(limite);fecharBanco();console.log(falhou?'Busca: FALHOU':'Busca: APROVADA');app.exit(falhou?1:0);
}).catch(e=>{console.error(e);app.exit(1);});
